  test('when no blog posts', () => {
    const result = mostLikes([])
    assert.equal(null, result)
  })

  test('when there a couple of posts of different authors and number of likes', () => {
    const result = mostLikes([posts[0], posts[3], posts[4], posts[5]])
    assert.deepStrictEqual({ author: 'Robert C. Martin', likes: 12 }, result)
  })

  test('when there are multiple posts with different authors and number of likes', () => {
    const result = mostLikes(posts)
    assert.deepStrictEqual({ author: 'Edsger W. Dijkstra', likes: 17 }, result)
  })
